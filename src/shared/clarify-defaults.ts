export function continueClarifyTask(content: string, structured: boolean) {
  const suffix = "\n\n" + FIRST_CLARIFY_TASK;
  return (
    (structured && content.endsWith(suffix)
      ? content.slice(0, -suffix.length)
      : content) +
    "\n\n" +
    (structured
      ? CONTINUE_CLARIFY_TASK
      : "用户明确要求继续提问，请至少提出一个尚未问过、未回答或跳过的新问题，不得只回答无。保留原来的提问格式，不代写正文。")
  );
}
